import AppKit
import Foundation

/// Snapshot of the macOS pasteboard without leaking concealed/transient secrets.
struct ClipboardSnapshot: Equatable, Sendable {
    let text: String?
    let isConcealed: Bool
}

@MainActor protocol ClipboardAccess {
    func readSnapshot() -> ClipboardSnapshot
    func writeString(_ text: String) -> Bool
}

@MainActor final class MacClipboardAccess: ClipboardAccess {
    /// Standard macOS pasteboard markers used by 1Password, Bitwarden, Keychain, etc.
    static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    func readSnapshot() -> ClipboardSnapshot {
        let pb = NSPasteboard.general
        if let types = pb.types, types.contains(where: { Self.sensitiveTypes.contains($0) }) {
            return ClipboardSnapshot(text: nil, isConcealed: true)
        }
        if let items = pb.pasteboardItems {
            for item in items where item.types.contains(where: { Self.sensitiveTypes.contains($0) }) {
                return ClipboardSnapshot(text: nil, isConcealed: true)
            }
        }
        return ClipboardSnapshot(text: pb.string(forType: .string), isConcealed: false)
    }

    func writeString(_ text: String) -> Bool {
        let pb = NSPasteboard.general
        pb.clearContents()
        return pb.setString(text, forType: .string)
    }
}

/// Masks API keys, Bearer tokens, PEM private keys, JWTs, and long high-entropy tokens
/// before any preview or cloud model transmission.
enum ClipboardSecretMasker {
    static let redactionMarker = "[секрет приховано]"

    private static let patterns: [NSRegularExpression] = [
        // PEM private key blocks (multiline).
        #"(?s)-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----.*?-----END [A-Z0-9 ]*PRIVATE KEY-----"#,
        // JWT tokens (header.payload.signature).
        #"(?<![A-Za-z0-9_-])eyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}(?![A-Za-z0-9_-])"#,
        // Bearer tokens.
        #"(?i)\bBearer\s+[A-Za-z0-9._~+/=-]{20,}"#,
        // OpenAI-style keys (sk-, sk-proj-).
        #"(?<![A-Za-z0-9])sk-[A-Za-z0-9_-]{20,}"#,
        // ElevenLabs-style keys.
        #"(?<![A-Za-z0-9])sk_[A-Za-z0-9]{20,}"#,
        // Bare long hex strings (32+ hex chars).
        #"(?<![A-Za-z0-9_-])[0-9a-fA-F]{32,}(?![A-Za-z0-9_-])"#,
    ].compactMap { try? NSRegularExpression(pattern: $0) }

    private static let longToken = try? NSRegularExpression(
        pattern: #"(?<![A-Za-z0-9_-])[A-Za-z0-9_-]{32,}(?![A-Za-z0-9_-])"#
    )

    static func mask(_ text: String) -> (masked: String, secretsMasked: Bool) {
        var result = text
        let template = NSRegularExpression.escapedTemplate(for: redactionMarker)
        for regex in patterns {
            let range = NSRange(result.startIndex..., in: result)
            result = regex.stringByReplacingMatches(in: result, range: range, withTemplate: template)
        }
        if let longToken {
            let ns = result as NSString
            let matches = longToken.matches(in: result, range: NSRange(location: 0, length: ns.length))
            for match in matches.reversed() {
                let token = ns.substring(with: match.range)
                if token.contains(where: \.isLetter) && token.contains(where: \.isNumber) {
                    result = (result as NSString).replacingCharacters(in: match.range, with: redactionMarker)
                }
            }
        }
        return (result, result != text)
    }
}

struct ClipboardReadInspection: Equatable, Sendable {
    let fencedText: String
    /// First 80 characters formed strictly AFTER secret masking.
    let preview: String
    let characterCount: Int
    let truncated: Bool
    let secretsMasked: Bool
    /// Owner decision #1 (25.11.2026): .immediate only when request explicitly mentions
    /// "буфер"/"clipboard", length <= 500, no secrets masked, and no concealed types.
    let allowsImmediate: Bool
}

@MainActor final class ClipboardActions {
    static let maxReadChars = 8_000
    static let maxWriteChars = 16_000
    static let immediateMaxChars = 500
    static let undoTTLSeconds: TimeInterval = 120

    enum InspectResult: Equatable, Sendable {
        case ready(ClipboardReadInspection)
        case blockedConcealed
        case empty
    }

    private let access: ClipboardAccess
    private let uptime: () -> TimeInterval
    private var undoSlot: (text: String, expiresAt: TimeInterval)?

    init(access: ClipboardAccess? = nil,
         uptime: @escaping () -> TimeInterval = { ProcessInfo.processInfo.systemUptime }) {
        self.access = access ?? MacClipboardAccess()
        self.uptime = uptime
    }

    /// Clears the in-RAM undo slot (called on clearSnapshots / cancel / new turn).
    func clearUndo() {
        undoSlot = nil
    }

    static func requestMentionsClipboard(_ request: String) -> Bool {
        let lower = request.lowercased()
        return lower.contains("буфер") || lower.contains("clipboard")
    }

    func inspectForRead(requestText: String) -> InspectResult {
        let snapshot = access.readSnapshot()
        if snapshot.isConcealed { return .blockedConcealed }
        guard let raw = snapshot.text, !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return .empty
        }
        let truncated = raw.count > Self.maxReadChars
        let bounded = truncated ? String(raw.prefix(Self.maxReadChars)) : raw
        let (masked, secretsMasked) = ClipboardSecretMasker.mask(bounded)
        let preview = UISnapshotText.truncate(UISnapshotText.clean(masked), maxChars: 80)
        let id = String(UUID().uuidString.replacingOccurrences(of: "-", with: "").prefix(8)).lowercased()
        let body = "# clipboard id=\(id) chars=\(raw.count) truncated=\(truncated) masked=\(secretsMasked)\n\(masked)"
        let fenced = UISnapshotText.fence(snapshotID: id, body: body)
        let immediate = Self.requestMentionsClipboard(requestText)
            && !secretsMasked
            && raw.count <= Self.immediateMaxChars
        return .ready(ClipboardReadInspection(
            fencedText: fenced,
            preview: preview,
            characterCount: raw.count,
            truncated: truncated,
            secretsMasked: secretsMasked,
            allowsImmediate: immediate
        ))
    }

    func read(language: String, requestText: String = "", ownerConsented: Bool) -> CommandOutcome {
        guard language == "uk" || language == "en" else {
            return .failed(reason: "Оберіть українську або англійську мову.")
        }
        switch inspectForRead(requestText: requestText) {
        case .blockedConcealed:
            return .failed(reason: actionText(
                language,
                "Буфер містить захищені дані (менеджер паролів або тимчасовий запис). Читання заблоковано.",
                "The clipboard contains concealed or transient data. Reading is blocked."
            ))
        case .empty:
            return .failed(reason: actionText(
                language,
                "Буфер обміну порожній або не містить тексту.",
                "The clipboard is empty or does not contain text."
            ))
        case .ready(let info):
            guard ownerConsented || info.allowsImmediate else {
                return .failed(reason: actionText(
                    language,
                    "Читання буфера обміну потребує вашого підтвердження на екрані.",
                    "Reading the clipboard requires your confirmation on screen."
                ))
            }
            return .done(summary: info.fencedText)
        }
    }

    func write(_ text: String, language: String) -> CommandOutcome {
        guard language == "uk" || language == "en" else {
            return .failed(reason: "Оберіть українську або англійську мову.")
        }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxWriteChars else {
            return .failed(reason: actionText(language, "Некоректний текст для буфера обміну.", "Invalid clipboard text."))
        }
        let previous = access.readSnapshot()
        if previous.isConcealed {
            // Never cache concealed/transient secrets in RAM undo slot.
            undoSlot = nil
        } else if let prevText = previous.text, !prevText.isEmpty, prevText.count <= Self.maxWriteChars {
            undoSlot = (text: prevText, expiresAt: uptime() + Self.undoTTLSeconds)
        } else {
            undoSlot = nil
        }
        guard access.writeString(text) else {
            return .failed(reason: actionText(language, "Не вдалося записати в буфер обміну.", "Could not write to the clipboard."))
        }
        return .done(summary: actionText(language, "Результат скопійовано в буфер обміну.", "Copied the result to the clipboard."))
    }

    func undo(language: String) -> CommandOutcome {
        guard language == "uk" || language == "en" else {
            return .failed(reason: "Оберіть українську або англійську мову.")
        }
        guard let slot = undoSlot else {
            return .failed(reason: actionText(language, "Немає збереженого попереднього буфера.", "No previous clipboard entry is available."))
        }
        undoSlot = nil
        guard slot.expiresAt >= uptime() else {
            return .failed(reason: actionText(language, "Попередній буфер уже очищено за таймаутом.", "The previous clipboard entry expired."))
        }
        guard access.writeString(slot.text) else {
            return .failed(reason: actionText(language, "Не вдалося відновити буфер обміну.", "Could not restore the clipboard."))
        }
        return .done(summary: actionText(language, "Попередній буфер обміну відновлено.", "Restored the previous clipboard."))
    }

    func paste(_ text: String, dictation: DictationActions?, token: UUID?, language: String) -> CommandOutcome {
        guard language == "uk" || language == "en" else {
            return .failed(reason: "Оберіть українську або англійську мову.")
        }
        let writeOutcome = write(text, language: language)
        guard case .done = writeOutcome else { return writeOutcome }
        guard let dictation else {
            return .partial(
                summary: actionText(language, "Скопійовано в буфер обміну, але вставлення не підключено.", "Copied to the clipboard, but insertion is not connected."),
                details: actionText(language, "Натисніть ⌘V, щоб вставити.", "Press ⌘V to paste.")
            )
        }
        let insertOutcome = dictation.insert(text, token: token, language: language)
        switch insertOutcome {
        case .done:
            return .done(summary: actionText(language, "Результат скопійовано й вставлено.", "Copied and inserted the result."))
        case .partial(let summary, let details):
            return .partial(summary: summary, details: details)
        case .failed(let reason):
            return .partial(
                summary: actionText(language, "Скопійовано в буфер обміну, але вставити в активне поле не вдалося.", "Copied to the clipboard, but could not insert into the active field."),
                details: reason
            )
        default:
            return writeOutcome
        }
    }
}
