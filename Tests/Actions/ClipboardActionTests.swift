import AppKit
import Foundation

@MainActor
private final class FakeClipboardAccess: ClipboardAccess {
    var snapshot = ClipboardSnapshot(text: nil, isConcealed: false)
    private(set) var writes: [String] = []
    var writeSucceeds = true

    func readSnapshot() -> ClipboardSnapshot { snapshot }
    func writeString(_ text: String) -> Bool {
        writes.append(text)
        guard writeSucceeds else { return false }
        snapshot = ClipboardSnapshot(text: text, isConcealed: false)
        return true
    }
}

@MainActor
private final class DummyClipboardWorkspace: ActionWorkspace {
    func resolveApplication(_ name: String) -> URL? { nil }
    func openApplication(_ url: URL) async throws -> Bool { false }
    func activateApplication(_ url: URL) async throws -> Bool { false }
    func quitApplication(_ url: URL) async throws -> Bool { false }
    func openWebURL(_ url: URL) throws -> Bool { false }
}

private final class TestClock: @unchecked Sendable {
    var now: TimeInterval = 100
}

@main struct ClipboardActionTests {
    static func main() async throws {
        var count = 0
        func check(_ ok: Bool, _ label: String) {
            guard ok else { fatalError("FAIL: \(label)") }
            count += 1
        }

        // 0. Sensitive pasteboard types include all three macOS password-manager markers.
        let sensitive = MacClipboardAccess.sensitiveTypes
        check(sensitive.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")), "ConcealedType guarded")
        check(sensitive.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType")), "TransientType guarded")
        check(sensitive.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")), "AutoGeneratedType guarded")

        let access = await MainActor.run { FakeClipboardAccess() }
        let clock = TestClock()
        let clipboard = await MainActor.run { ClipboardActions(access: access, uptime: { clock.now }) }

        // 1. Empty clipboard.
        let emptyInspect = await MainActor.run { clipboard.inspectForRead(requestText: "переклади буфер") }
        check(emptyInspect == .empty, "Empty clipboard detected")

        // 2. Concealed / transient clipboard is strictly blocked.
        await MainActor.run { access.snapshot = ClipboardSnapshot(text: "super-secret-pass", isConcealed: true) }
        let concealedInspect = await MainActor.run { clipboard.inspectForRead(requestText: "переклади буфер") }
        check(concealedInspect == .blockedConcealed, "Concealed clipboard blocked in inspect")
        let concealedRead = await MainActor.run { clipboard.read(language: "uk", requestText: "переклади буфер", ownerConsented: true) }
        if case .failed(let reason) = concealedRead {
            check(reason.contains("захищені"), "Concealed clipboard blocked even with ownerConsented")
        } else { check(false, "Expected failure for concealed clipboard") }

        // 3. clipboardWrite MUST NOT cache concealed previous clipboard in RAM undo slot.
        let writeOverConcealed = await MainActor.run { clipboard.write("public output", language: "uk") }
        if case .done = writeOverConcealed { count += 1 } else { check(false, "Write over concealed should succeed") }
        let undoAfterConcealed = await MainActor.run { clipboard.undo(language: "uk") }
        if case .failed = undoAfterConcealed { count += 1 } else { check(false, "Undo must not restore concealed secret") }

        // 4. Secret masking (OpenAI key, JWT, PEM private key, Bearer) + preview formed strictly AFTER masking.
        let jwt = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJV_adQssw5c"
        let openAIKey = "sk-proj-1234567890abcdefghijklmnop"
        let pem = "-----BEGIN RSA PRIVATE KEY-----\nMIIEowIBAAKCAQEAtestkeydata\n-----END RSA PRIVATE KEY-----"
        let rawWithSecrets = "Key \(openAIKey) and \(jwt) and \(pem)"
        await MainActor.run { access.snapshot = ClipboardSnapshot(text: rawWithSecrets, isConcealed: false) }
        let secretInspect = await MainActor.run { clipboard.inspectForRead(requestText: "переклади буфер") }
        if case .ready(let info) = secretInspect {
            check(info.secretsMasked, "Secrets flagged as masked")
            check(!info.allowsImmediate, "Owner decision #1: secrets present forces .confirmation")
            check(!info.preview.contains("sk-proj-"), "Preview has no raw OpenAI key")
            check(!info.preview.contains("eyJhbGci"), "Preview has no raw JWT")
            check(!info.preview.contains("MIIEowIB"), "Preview has no raw PEM body")
            check(info.preview.count <= 80, "Preview capped at 80 chars")
            check(!info.fencedText.contains("sk-proj-") && !info.fencedText.contains("eyJhbGci") && !info.fencedText.contains("MIIEowIB"), "Fenced text has no raw secrets")
            check(info.fencedText.contains("<UNTRUSTED_UI_SNAPSHOT_"), "Clipboard text is fenced for memory redaction")
        } else { check(false, "Expected ready inspection with secrets masked") }

        // 5. Owner decision #1: .immediate vs .confirmation matrix.
        await MainActor.run { access.snapshot = ClipboardSnapshot(text: "Привіт, як справи?", isConcealed: false) }
        let okUK = await MainActor.run { clipboard.inspectForRead(requestText: "переклади буфер англійською") }
        if case .ready(let info) = okUK { check(info.allowsImmediate && !info.secretsMasked, "uk explicit 'буфер' <=500 no secrets -> immediate") }
        else { check(false, "Expected ready") }

        let okEN = await MainActor.run { clipboard.inspectForRead(requestText: "summarize my clipboard") }
        if case .ready(let info) = okEN { check(info.allowsImmediate, "en explicit 'clipboard' <=500 no secrets -> immediate") }
        else { check(false, "Expected ready") }

        let noMention = await MainActor.run { clipboard.inspectForRead(requestText: "переклади це англійською") }
        if case .ready(let info) = noMention { check(!info.allowsImmediate, "No explicit 'буфер'/'clipboard' -> confirmation") }
        else { check(false, "Expected ready") }

        let immediateRead = await MainActor.run { clipboard.read(language: "uk", requestText: "переклади буфер", ownerConsented: false) }
        if case .done(let fenced) = immediateRead {
            check(fenced.contains("Привіт, як справи?"), "Immediate read returns fenced text")
        } else { check(false, "Expected immediate read to succeed") }

        let unconsentedNoMention = await MainActor.run { clipboard.read(language: "uk", requestText: "переклади це", ownerConsented: false) }
        if case .failed = unconsentedNoMention { count += 1 } else { check(false, "Unconsented read without mention must fail") }

        // > 500 chars forces confirmation even with explicit "буфер".
        let long501 = String(repeating: "а", count: 501)
        await MainActor.run { access.snapshot = ClipboardSnapshot(text: long501, isConcealed: false) }
        let over500 = await MainActor.run { clipboard.inspectForRead(requestText: "стисни буфер") }
        if case .ready(let info) = over500 {
            check(!info.allowsImmediate && info.characterCount == 501, ">500 chars forces confirmation")
        } else { check(false, "Expected ready") }

        // > 8000 chars truncates to 8000.
        let huge9000 = String(repeating: "x", count: 9_000)
        await MainActor.run { access.snapshot = ClipboardSnapshot(text: huge9000, isConcealed: false) }
        let over8k = await MainActor.run { clipboard.inspectForRead(requestText: "summarize clipboard") }
        if case .ready(let info) = over8k {
            check(info.truncated && info.characterCount == 9_000 && !info.allowsImmediate, ">8000 chars marked truncated")
            check(info.fencedText.count < 8_600 && !info.fencedText.contains(String(repeating: "x", count: 8_001)), "Fenced payload bounded to 8000 chars")
        } else { check(false, "Expected ready") }

        // 6. Registry limits (16k write/paste, empty rejected) and policies.
        let registry = ActionRegistry()
        check(registry.policy(for: .clipboardRead) == .confirmation, "Registry clipboardRead policy is confirmation")
        check(registry.policy(for: .clipboardPaste("hi")) == .confirmation, "Registry clipboardPaste policy is confirmation")
        check(registry.policy(for: .clipboardWrite("hi")) == .immediate, "Registry clipboardWrite policy is immediate")
        check(registry.policy(for: .clipboardUndo) == .immediate, "Registry clipboardUndo policy is immediate")
        do { try registry.validate(.clipboardWrite(String(repeating: "a", count: 16_001))); check(false, "16001 write rejected") }
        catch ActionError.invalidParameters { count += 1 }
        do { try registry.validate(.clipboardPaste("   ")); check(false, "Empty paste rejected") }
        catch ActionError.invalidParameters { count += 1 }

        // 7. clipboardUndo + TTL 120s + clearUISnapshots() + HistoryStore privacy.
        let tmpDir = URL(fileURLWithPath: "/tmp/jarvis-clipboard-tests-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: tmpDir) }
        let history = try HistoryStore(directory: tmpDir.appendingPathComponent("history", isDirectory: true))
        let dummyWorkspace = await MainActor.run { DummyClipboardWorkspace() }
        let executor = ActionExecutor(workspace: dummyWorkspace, history: history, clipboard: clipboard)

        await MainActor.run { access.snapshot = ClipboardSnapshot(text: "Original text", isConcealed: false) }
        let writeOutcome = await executor.handle(action: .clipboardWrite("Translated text"), language: "uk")
        if case .done = writeOutcome { count += 1 } else { check(false, "Write succeeded") }
        check(await MainActor.run { access.snapshot.text == "Translated text" }, "Clipboard updated")

        // IntentParser triggers uk/en for clipboardUndo.
        let parser = IntentParser()
        check(parser.parse("Поверни попередній буфер.", language: "uk") == .clipboardUndo, "uk undo parsed")
        check(parser.parse("restore previous clipboard", language: "en") == .clipboardUndo, "en undo parsed")

        // Undo within TTL succeeds.
        clock.now = 150
        let undoOutcome = await executor.handle("Поверни попередній буфер", language: "uk")
        if case .done = undoOutcome { count += 1 } else { check(false, "Undo within TTL succeeded") }
        check(await MainActor.run { access.snapshot.text == "Original text" }, "Previous clipboard restored")

        // Undo after TTL 120s fails.
        _ = await executor.handle(action: .clipboardWrite("Second text"), language: "en")
        clock.now = 271 // 150 + 121
        let expiredUndo = await executor.handle(action: .clipboardUndo, language: "en")
        if case .failed(let reason) = expiredUndo {
            check(reason.contains("expired"), "Expired undo rejected")
        } else { check(false, "Expected expired undo failure") }

        // clearUISnapshots clears undo slot.
        clock.now = 300
        _ = await executor.handle(action: .clipboardWrite("Third text"), language: "uk")
        await MainActor.run { executor.clearUISnapshots() }
        let clearedUndo = await executor.handle(action: .clipboardUndo, language: "uk")
        if case .failed = clearedUndo { count += 1 } else { check(false, "clearUISnapshots clears undo slot") }

        // HistoryStore leaks zero clipboard contents.
        let records = try await history.read()
        check(records.contains(where: { $0.action == "clipboardWrite" }) && records.contains(where: { $0.action == "clipboardUndo" }), "History records action kinds")
        let rawHistory = try String(contentsOf: tmpDir.appendingPathComponent("history/history.jsonl"), encoding: .utf8)
        check(!rawHistory.contains("Original text") && !rawHistory.contains("Translated text") && !rawHistory.contains("Third text"), "History leaks zero clipboard text")

        print("Clipboard action tests: \(count) checks passed")
    }
}
